class BuiltInScreenTranslationGlossaryRepository {

    fun findForLabel(label: String): ScreenTranslationGlossary? {
        val normalized = label.lowercase()
            .replace('_', ' ')
            .replace('-', ' ')
            .replace(Regex("\\s+"), " ")
            .trim()
        if (!normalized.isFinalFantasyViLabel()) return null
        return finalFantasyVi
    }

    private fun String.isFinalFantasyViLabel(): Boolean =
        contains("final fantasy vi") ||
            contains("final fantasy 6") ||
            contains("final fantasy iii") ||
            contains("最终幻想6") ||
            contains("最终幻想vi") ||
            contains("太空战士6") ||
            contains("太空战士vi")

